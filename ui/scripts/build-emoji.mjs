// G-27: builds src/emoji/data.json, the emoji picker's bundled list (spec:
// docs/ux/specs/emoji-picker.md §2). Run it by hand when the pinned versions
// below change, then commit the output. The app never fetches anything.
//
//   docker compose run --rm ui node --experimental-strip-types scripts/build-emoji.mjs [srcDir]
//
// Sources (pinned):
// - Unicode emoji-test.txt: the order, the groups, the emoji version and the
//   English name of every fully-qualified emoji.
// - CLDR annotations (en and he, plus the derived ones for sequences): names
//   ("tts") and keywords ("default"). Data © Unicode, Inc., Unicode-3.0
//   licence (https://www.unicode.org/license.txt); the output keeps that notice.
//
// What's kept: fully-qualified emoji up to MAX_VERSION (what Windows 11's
// Segoe UI Emoji in our Electron renders, so no tofu), without the Component
// group, skin-tone variants or subdivision flags, and only what passes the
// core's reaction check (normalizeEmoji), so every cell can also be a reaction.
// With srcDir, the files are read from there (emoji-test.txt, ann-en.json,
// ann-he.json, der-en.json, der-he.json); otherwise they're downloaded.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { normalizeEmoji } from '../src/core/emoji.ts';

const EMOJI_VERSION = '16.0';
const CLDR_VERSION = '49.0.0';
const MAX_VERSION = 15.0;

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../src/emoji/data.json');
const srcDir = process.argv[2];

const URLS = {
  'emoji-test.txt': `https://unicode.org/Public/emoji/${EMOJI_VERSION}/emoji-test.txt`,
  ...Object.fromEntries(
    ['en', 'he'].flatMap((l) => [
      [`ann-${l}.json`, `https://raw.githubusercontent.com/unicode-org/cldr-json/${CLDR_VERSION}/cldr-json/cldr-annotations-full/annotations/${l}/annotations.json`],
      [`der-${l}.json`, `https://raw.githubusercontent.com/unicode-org/cldr-json/${CLDR_VERSION}/cldr-json/cldr-annotations-derived-full/annotationsDerived/${l}/annotations.json`],
    ]),
  ),
};

async function source(name) {
  if (srcDir) return readFileSync(join(srcDir, name), 'utf8');
  const r = await fetch(URLS[name]);
  if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
  return r.text();
}

/** The groups in emoji-test.txt order, as the picker's section keys. */
const GROUPS = {
  'Smileys & Emotion': 'smileys',
  'People & Body': 'people',
  'Animals & Nature': 'nature',
  'Food & Drink': 'food',
  'Travel & Places': 'travel',
  Activities: 'activities',
  Objects: 'objects',
  Symbols: 'symbols',
  Flags: 'flags',
};

const isSkinTone = (c) => c >= 0x1f3fb && c <= 0x1f3ff;
const isTag = (c) => c >= 0xe0020 && c <= 0xe007f;

function annotations(json, derived) {
  const a = JSON.parse(json).annotations.annotations;
  const d = JSON.parse(derived).annotationsDerived.annotations;
  return { ...d, ...a };
}

/** The CLDR keys leave out VS16; try the glyph as is first. */
function lookup(table, glyph) {
  return table[glyph] ?? table[glyph.replaceAll('️', '')];
}

const clean = (s) => s.replace(/\s+/g, ' ').trim();

const [test, annEn, annHe, derEn, derHe] = await Promise.all(
  ['emoji-test.txt', 'ann-en.json', 'ann-he.json', 'der-en.json', 'der-he.json'].map(source),
);
const en = annotations(annEn, derEn);
const he = annotations(annHe, derHe);

const groups = Object.values(GROUPS);
const list = [];
let group = null;
let noHe = 0;
for (const line of test.split('\n')) {
  const g = /^# group: (.+)$/.exec(line);
  if (g) {
    group = GROUPS[g[1].trim()] ?? null; // Component → null
    continue;
  }
  const m = /^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.+)$/.exec(line);
  if (!m || !group) continue;
  const [, glyph, version, name] = m;
  if (Number(version) > MAX_VERSION) continue;
  const cps = [...glyph].map((c) => c.codePointAt(0));
  if (cps.some(isSkinTone) || cps.some(isTag)) continue;
  if (normalizeEmoji(glyph) === null) continue;
  const e = lookup(en, glyph);
  const h = lookup(he, glyph);
  if (!h?.tts) noHe++;
  list.push([
    glyph,
    groups.indexOf(group),
    clean(e?.tts?.[0] ?? name),
    clean((e?.default ?? []).join(' | ')),
    clean(h?.tts?.[0] ?? ''),
    clean((h?.default ?? []).join(' | ')),
  ]);
}

mkdirSync(dirname(out), { recursive: true });
const data = {
  notice: `Generated by scripts/build-emoji.mjs from Unicode emoji ${EMOJI_VERSION} (emoji-test.txt) and CLDR ${CLDR_VERSION} annotations (en, he). Data © Unicode, Inc. Unicode-3.0 licence: https://www.unicode.org/license.txt`,
  groups,
  /** [glyph, group index, en name, en keywords, he name, he keywords]; keywords are " | "-separated. */
  emoji: list,
};
writeFileSync(out, JSON.stringify(data) + '\n');
console.log(`${list.length} emoji in ${groups.length} groups (${noHe} without a Hebrew name) → src/emoji/data.json`);
